#!/usr/bin/env python
"""Generate docs/dependency-licenses.md from the *installed* package metadata (not from memory).

Walks the dependency closure of requirements.txt, reads each distribution's declared licence
(License-Expression / License / Trove classifiers) and flags anything copyleft or undeclared for human review.

    python scripts/audit_licenses.py            # rewrite docs/dependency-licenses.md
    python scripts/audit_licenses.py --check    # exit 1 if a REVIEW item exists (used in CI)
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COPYLEFT = re.compile(r"\b(AGPL|GPL|LGPL|SSPL|EUPL|CC-BY-NC|Commons Clause)\b", re.I)
PERMISSIVE = re.compile(
    r"\b(MIT|BSD|Apache|ISC|PSF|Python Software Foundation|HPND|Zlib|MPL|Unlicense|CC0|PIL|Pillow|0BSD|BlueOak)\b", re.I
)


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_requirements() -> list[str]:
    out = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if line and not line.startswith("-"):
            out.append(norm(re.split(r"[<>=!~\[ ]", line)[0]))
    return out


def closure(roots: list[str]) -> dict[str, metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = list(roots)
    while todo:
        n = norm(todo.pop())
        if n in seen:
            continue
        try:
            d = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            continue
        seen[n] = d
        for r in d.requires or []:
            if "extra ==" in r:
                continue
            todo.append(re.split(r"[<>=!~\[ ;(]", r)[0])
    return seen


def licence_of(d: metadata.Distribution) -> str:
    md = d.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr
    lic = (md.get("License") or "").strip()
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    if cls:
        return "; ".join(cls)
    if lic:
        return lic.splitlines()[0][:80] + " …"
    return "UNDECLARED"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    roots = direct_requirements()
    dists = closure(roots)
    rows, review = [], []
    for n, d in sorted(dists.items()):
        lic = licence_of(d)
        direct = n in roots
        status = "OK"
        if COPYLEFT.search(lic):
            status = "REVIEW (copyleft)"
        elif lic == "UNDECLARED" or not PERMISSIVE.search(lic):
            status = "REVIEW (verify)"
        if status != "OK":
            review.append((n, lic, status))
        rows.append(
            (
                d.metadata["Name"],
                d.version,
                lic,
                "direct" if direct else "transitive",
                status,
                d.metadata.get("Home-page") or "",
            )
        )
    lines = [
        "# Dependency licences",
        "",
        "> Generated by `scripts/audit_licenses.py` from the metadata of the packages actually installed "
        f"({time.strftime('%Y-%m-%d', time.gmtime())}, Python {sys.version.split()[0]}). Re-run after changing `requirements.txt`; CI fails on an unreviewed copyleft/undeclared licence.",
        "",
        "Scope: runtime closure of `requirements.txt` (the CPU-safe Studio). The AI extras (`requirements-triposr.txt`) and model weights are documented in [models/model-licenses.md](models/model-licenses.md).",
        "",
        "| Package | Version | Declared licence | Kind | Status |",
        "|---|---|---|---|---|",
    ]
    for name, ver, lic, kind, status, _home in rows:
        lines.append(f"| {name} | {ver} | {lic.replace('|', '/')} | {kind} | {status} |")
    lines += [
        "",
        "## Bundled front-end (not installed via pip)",
        "",
        "| Component | Version | Licence | Notes |",
        "|---|---|---|---|",
        "| three.js (+ OrbitControls, GLTFLoader, RoomEnvironment) | 0.186.1 | MIT | Bundled with esbuild into `ui/static/vendor/three-viewer.min.js`; licence text at `ui/static/vendor/THREE-LICENSE.txt`; rebuild with `scripts/build_vendor.sh`. |",
        "| esbuild (build-time only) | 0.25.0 | MIT | Not shipped. |",
        "| gltf-validator (CI/dev only) | npm latest | Apache-2.0 | Khronos Group validator; not shipped. |",
        "",
        "## Review items",
        "",
    ]
    if review:
        lines += [f"* **{n}** — `{lic}` — {st}" for n, lic, st in review]
        lines += [
            "",
            "Review each item manually (read the package's licence file) before relying on it in production. A package listed here is **not** assumed to be acceptable.",
        ]
    else:
        lines.append(
            "None: every package in the runtime closure declares a permissive licence (MIT / BSD / Apache-2.0 / HPND / PSF / MPL-2.0 or similar). MPL-2.0 is file-level copyleft: we do not modify those files."
        )
    lines += [
        "",
        "## Notes",
        "",
        "* Declared licences come from package metadata, which can be wrong or incomplete; this audit is a screening step, not legal advice.",
        "* `xatlas` (UV unwrapping) wraps the MIT-licensed xatlas library.",
        "* `manifold3d` is intentionally not a dependency.",
        "",
    ]
    out = ROOT / "docs" / "dependency-licenses.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} packages audited, {len(review)} need review -> {out.relative_to(ROOT)}")
    for n, lic, st in review:
        print(f"  {st}: {n}: {lic}")
    return 1 if (args.check and review) else 0


if __name__ == "__main__":
    raise SystemExit(main())
